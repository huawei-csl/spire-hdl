class MyRecord(TemplateRecord):
    a = Wire(UInt(8))
    b = Wire(UInt(4))


class RecordWithArray(TemplateRecord):
    a   = Wire(UInt(8))
    vec = Array([Wire(UInt(2)) for _ in range(3)])  # 3×2 bits


