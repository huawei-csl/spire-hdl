class LakeNotFoundError(RuntimeError):
    """`lake` is not on PATH, so generated proofs cannot be checked."""


class LeanBuildError(RuntimeError):
    """`lake build` (or a check file) reported errors."""


class ProofCheckError(RuntimeError):
    """A proof compiled but does not establish the spec, or relies on disallowed axioms."""


def write_lean_project(lean_dir: Path, roots: Iterable[str], *,
                       package: str = 'spireAutoLeanMatmul',
                       lib: str = 'SpireAutoLeanMatmul') -> Dict[str, Path]:
    """Write lakefile.lean, lean-toolchain and a copy of SpireSemantics.lean into lean_dir."""
    lean_dir = Path(lean_dir); lean_dir.mkdir(parents=True, exist_ok=True)
    all_roots = [SEMANTICS_MODULE] + [r for r in roots if r != SEMANTICS_MODULE]
    sem = lean_dir / f'{SEMANTICS_MODULE}.lean'
    sem.write_text(SEMANTICS_FILE.read_text())
    root_lines = ',\n'.join(f'    `{r}' for r in all_roots)
    lakefile = lean_dir / 'lakefile.lean'
    lakefile.write_text(
        '-- Generated by spire.design_db.lean.bridge.write_lean_project; do not edit.\n'
        'import Lake\nopen Lake DSL\n\n'
        f'package «{package}» where\n\n'
        '@[default_target]\n'
        f'lean_lib «{lib}» where\n'
        f'  roots := #[\n{root_lines}\n  ]\n')
    toolchain = lean_dir / 'lean-toolchain'
    toolchain.write_text(LEAN_TOOLCHAIN + '\n')
    return {'semantics': sem, 'lakefile': lakefile, 'toolchain': toolchain}


def find_lake() -> str:
    lake = shutil.which('lake')
    if lake is None:
        raise LakeNotFoundError(
            '`lake` (the Lean 4 build tool) is not on PATH, so the generated proofs cannot be '
            'checked. Install elan (https://github.com/leanprover/elan) and make sure '
            '~/.elan/bin (or $ELAN_HOME/bin) is on PATH.')
    return lake


def lake_build(lean_dir: Path, *targets: str, timeout: float = 900) -> str:
    """Run `lake build [targets]` in lean_dir. Raises LakeNotFoundError / LeanBuildError; returns the log."""
    lake = find_lake()
    proc = subprocess.run([lake, 'build', *targets], cwd=str(lean_dir), capture_output=True, text=True, timeout=timeout)
    log = proc.stdout + proc.stderr
    if proc.returncode != 0:
        raise LeanBuildError(f'lake build failed in {lean_dir} (exit {proc.returncode}):\n{log}')
    return log


# --------------------------------------------------------------------------------------
# Proof checker: the proof file is the only editable one, so after `lake build` we verify
# that its final theorem still has the spec's type and uses only allowed axioms.
# --------------------------------------------------------------------------------------

@dataclass(frozen=True)
class TheoremCheck:
    module: str          # proof module to import, e.g. BalancedMmacProof
    theorem: str         # fully qualified, e.g. BalancedMmacProof.implements_mmac
    expected_type: str   # e.g. MmacSpec.Correct BalancedMmacCircuit.eval


BASE_AXIOMS = {'propext', 'Classical.choice', 'Quot.sound'}
# Statement head of the per-declaration axiom `bv_decide` introduces when it trusts the native LRAT
# checker. Axioms are admitted by their *type*, never by their name: names are author-controlled
# (a forged `axiom x._native.bv_decide.ax_1_1 : False` must be rejected).
BV_DECIDE_CERT_HEAD = 'Std.Tactic.BVDecide.Reflect.verifyBVExpr'

_AX_LINE = re.compile(r'AXIOM (?P<thm>\S+) (?P<name>\S+) \| module=(?P<module>\S+) \| type=(?P<type>.*)$')

# One report per theorem; every line is tagged with the theorem so no block splitting is needed.
_AXIOM_REPORT = (
    "open Lean Meta in\n"
    "run_meta do\n"
    "  let env ← getEnv\n"
    "  let axs ← collectAxioms ``{thm}\n"
    "  for ax in axs do\n"
    "    let modName := match env.getModuleIdxFor? ax with\n"
    "      | some i => toString env.header.moduleNames[i.toNat]!\n"
    "      | none => \"<current file>\"\n"
    "    let ty := (env.find? ax).get!.type\n"
    "    logInfo m!\"AXIOM {thm} {{ax}} | module={{modName}} | type={{ty}}\"\n")


def _allowed_axiom(name: str, module: str, typ: str, check: TheoremCheck) -> bool:
    if name in BASE_AXIOMS: return True
    # bv_decide certificate axioms, identified by statement. Policy on top: not attached to the final
    # theorem itself (no whole-design SAT directly in `implements`; a heuristic, not a soundness rule).
    if typ.startswith(BV_DECIDE_CERT_HEAD):
        return not name.startswith(check.theorem + '.')
    return False


def check_theorems(lean_dir: Path, checks: Sequence[TheoremCheck], *, timeout: float = 300) -> Dict[str, List[str]]:
    """Type-check each theorem against its expected statement and audit its axioms.

    Returns {theorem: [axioms]}. Raises ProofCheckError if a theorem does not have the expected type
    (e.g. the statement was weakened) or depends on sorry / a disallowed axiom. Axioms are judged by
    their *statement* (with their origin module reported), never by their name.
    """
    lake = find_lake()
    L = ['-- GENERATED scratch file; deleted after the check.', 'import Lean']
    L += [f'import {c.module}' for c in checks]
    for c in checks:
        L.append(f'example : {c.expected_type} := {c.theorem}')
        L.append(_AXIOM_REPORT.format(thm=c.theorem))
    scratch = Path(lean_dir) / '_CheckProofs.lean'
    scratch.write_text('\n'.join(L) + '\n')
    try:
        proc = subprocess.run([lake, 'env', 'lean', scratch.name], cwd=str(lean_dir),
                              capture_output=True, text=True, timeout=timeout)
    finally:
        scratch.unlink(missing_ok=True)
    log = proc.stdout + proc.stderr
    if proc.returncode != 0:
        raise ProofCheckError('a proof does not establish its spec statement:\n' + log)
    found: Dict[str, List[Tuple[str, str, str]]] = {c.theorem: [] for c in checks}
    for line in log.splitlines():
        m = _AX_LINE.search(line)
        if m and m.group('thm') in found:
            found[m.group('thm')].append((m.group('name'), m.group('module'), m.group('type').strip()))
    axioms: Dict[str, List[str]] = {}
    for c in checks:
        rep = found[c.theorem]
        if not rep and 'AXIOM' not in log:
            raise ProofCheckError(f'no axiom report for {c.theorem}:\n{log}')
        axioms[c.theorem] = [n for n, _, _ in rep]
        bad = [f'{n} : {t[:50]} (declared in {mod})' for n, mod, t in rep if not _allowed_axiom(n, mod, t, c)]
        if bad:
            raise ProofCheckError(f'{c.theorem} depends on disallowed axioms {bad} '
                                  '(sorry, custom axiom, or SAT on the whole design)')
    return axioms
