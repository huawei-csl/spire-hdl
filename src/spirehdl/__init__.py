# Public API. `Component` is the one abstraction users author; IO is declared with
# `IORecord` + `Input`/`Output`; `Simulator` runs a Component or a Netlist. The flat
# netlist IR (`Netlist`, formerly `Module`) is intentionally NOT exported here — power
# users import it from `spirehdl.ir`. VERILOG_BANNER is defined above so the modules
# imported below (which do `from spirehdl import VERILOG_BANNER`) resolve cleanly.
# ---------------------------------------------------------------------------
